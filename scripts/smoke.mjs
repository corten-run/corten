// Browser smoke test of every runtime behavior, against the watchlist example, in Chromium, Firefox
// and WebKit (Playwright's builds: `npx playwright install chromium firefox webkit`).
// Usage: node scripts/smoke.mjs [http://localhost:18480] [chromium|firefox|webkit ...]
import { runSmoke } from "./smoke/helpers.mjs";
import { namedFormNavigation, generatedFormViews, formFailures, submitKeys, formSubmission } from "./smoke/forms.mjs";
import { patchParsing, patchFixtures } from "./smoke/patch-parsing.mjs";
import { openWatchlist } from "./smoke/fixtures.mjs";
import { handlerEncoding, handlerArguments } from "./smoke/handler-arguments.mjs";
import { screenRead } from "./smoke/screen-read.mjs";
import { styles } from "./smoke/styles.mjs";
import { viewHelpers } from "./smoke/views.mjs";
import { modules } from "./smoke/modules.mjs";
import { componentLifecycle } from "./smoke/component-lifecycle.mjs";
import { liveFragments, streamCompression, streamRecovery } from "./smoke/live-streams.mjs";
import { partReads, partsInPatches } from "./smoke/parts.mjs";
import { trustedTypes } from "./smoke/trusted-types.mjs";
import { submitQueue } from "./smoke/submit-queue.mjs";
import { busyForms } from "./smoke/busy.mjs";
import { sectionNavigation, redirects, guardedNavigation, shellChanges, navigationMarks, currentLinks, fragmentTargets, earlyNavigation } from "./smoke/navigation.mjs";
import { scroll } from "./smoke/scroll.mjs";
import { appendPatches, retainedPatchState } from "./smoke/patches.mjs";
import { history } from "./smoke/history.mjs";
import { pageWrites } from "./smoke/page-writes.mjs";
import { writeFailures } from "./smoke/write-failures.mjs";
import { feedRecovery } from "./smoke/feeds.mjs";
import { patchUploads, uploads } from "./smoke/uploads.mjs";
import { prefetch } from "./smoke/prefetch.mjs";
import { pageRefresh } from "./smoke/page-refresh.mjs";
import { dataClients } from "./smoke/data-clients.mjs";
import { withoutJs } from "./smoke/without-js.mjs";

// Areas run in order and share their pages, routes, and listeners.
await runSmoke(async (browser) => {
  await namedFormNavigation(browser);
  await generatedFormViews(browser);
  await patchParsing(browser);
  const { page, errors, swaps, noSwaps, live, feedSources, signsIn, failWatch, openFeeds, holdWatch, bug, cut, abandoned, openStreams, located, navRequests } = await openWatchlist(browser);
  await handlerEncoding(page);
  await patchFixtures(page, browser);
  await handlerArguments(browser);
  await screenRead(browser);
  await styles(browser, errors, swaps, noSwaps);
  await viewHelpers(page, browser);
  const { prices } = await modules(browser, live, page);
  await componentLifecycle(page, live, prices, feedSources, signsIn);
  await liveFragments(page);
  await partReads(page, browser, swaps, noSwaps);
  await streamCompression(page);
  await trustedTypes(page, browser);
  await formFailures(page, failWatch, openFeeds);
  const { zero } = await submitKeys(page, holdWatch, failWatch, errors, browser, bug, cut);
  await submitQueue(holdWatch, page, abandoned, errors, zero);
  const { redirectName } = await busyForms(page);
  const { sectors, styleLinks, noteBorder } = await sectionNavigation(feedSources, page, redirectName, openFeeds, holdWatch, abandoned, openStreams, swaps);
  await scroll(swaps, page, errors, browser, noSwaps);
  await appendPatches(browser, swaps, noSwaps);
  await redirects(browser, bug, page, live, sectors, swaps, styleLinks, noteBorder, noSwaps);
  await history(swaps, browser, noSwaps, errors);
  const { formatLoaded } = await guardedNavigation(page, browser, bug);
  await pageWrites(page, browser);
  await writeFailures(browser);
  await shellChanges(prices, page, formatLoaded, signsIn, swaps, noSwaps);
  await partsInPatches(page, openStreams, browser);
  await streamRecovery(page);
  await feedRecovery(page, errors, located);
  const { part } = await retainedPatchState(page, browser, errors);
  await navigationMarks(page);
  await patchUploads(errors, page, part);
  await currentLinks(browser, swaps, noSwaps);
  await fragmentTargets(browser);
  await prefetch(swaps, page, navRequests, browser, errors, noteBorder, noSwaps);
  await pageRefresh(page, swaps, noSwaps, errors, signsIn);
  await uploads(page, live, errors, signsIn);
  await dataClients(page, browser);
  await withoutJs(browser, signsIn);
  await earlyNavigation(browser);
  await formSubmission(browser);
});
