// Builds the client code the corten crate embeds, from the sources in crates/corten/js:
//   dist/corten.js  the runtime, minified (the source keeps its comments; browsers get none)
//   dist/format.js  numbers, money and dates for a script (a `%{..}` handler argument): a module of
//                   its own, which only pages whose handlers take a format load
//   dist/keys.js    shortcut() for a page-wide shortcut (`corten/keys`): a module of its own, which
//                   only apps whose scripts import it serve, preloaded with those scripts
//   dist/view.js    rows() and the helpers of the generated view classes, which Corten puts at
//                   the start of an app's corten/views module (one script: no extra request)
// `node scripts/build-js.mjs --check` fails when a built file is not what its source builds to, or
// when the runtime's size in README.md ("An 11.2 KB (brotli) runtime") is not the built file's, which
// a build writes there.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { brotliCompressSync, gzipSync } from "node:zlib";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const js = join(root, "crates", "corten", "js");
const check = process.argv.includes("--check");
const common = { bundle: true, format: "esm", minify: true, target: "es2022", legalComments: "none", write: false };
const outputs = [
  {
    name: "corten.js",
    entryPoints: [join(js, "corten.js")],
    banner: { js: "// Corten runtime (MIT). Built from crates/corten/js/corten.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "format.js",
    entryPoints: [join(js, "format.js")],
    banner: { js: "// Corten script formats (MIT). Built from crates/corten/js/format.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "keys.js",
    entryPoints: [join(js, "keys.js")],
    banner: { js: "// Corten keys (MIT). Built from crates/corten/js/keys.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "view.js",
    entryPoints: [join(js, "view.js")],
    // Not a module: corten::script::views_module puts the generated classes after it, in the
    // same module, and they call its helpers by name. Its exports become those names.
    wrap: (text) => {
      const exports = /export\{([^}]*)\};?\s*$/.exec(text);
      if (!exports) throw new Error("view.js: expected esbuild's export list at the end");
      const pairs = exports[1].split(",").map((p) => p.trim().split(/\s+as\s+/));
      const names = pairs.map(([local, name]) => name ?? local);
      const fields = pairs.map(([local, name]) => `${name ?? local}:${local}`);
      const body = text.slice(0, exports.index);
      return `// The app's views (#[component(view)]), generated by Corten. rows() and the helpers: built from crates/corten/js/view.js.\nconst{${names.join(",")}}=(()=>{${body}return{${fields.join(",")}}})();\n`;
    },
  },
];

let stale = 0;
for (const { name, wrap, ...options } of outputs) {
  const out = join(js, "dist", name);
  const result = await build({ ...common, ...options, outfile: out });
  const text = wrap ? wrap(result.outputFiles[0].text) : result.outputFiles[0].text;
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (check) {
    if (current !== text) {
      console.error(`${out} is stale: run npm run build:js`);
      stale += 1;
    }
  } else {
    writeFileSync(out, text);
    console.log(`${out}: ${text.length} B, ${gzipSync(text, { level: 9 }).length} B gzip`);
  }
}
// The README's headline size of the runtime: dist/corten.js, brotli at its default quality (11), in
// kB of 1,000 bytes. A check allows 0.1 KB, since another Node's brotli may differ by a few bytes.
const readme = join(root, "README.md");
const runtime = brotliCompressSync(readFileSync(join(js, "dist", "corten.js"))).length;
const said = /An? ([\d.]+) KB \(brotli\) runtime/;
// "an 11.2", "an 8.4", "a 12.5", as the number is read aloud.
const article = (/** @type {string} */ kb) => (/^(8|1[18](\.|$))/.test(kb) ? "An" : "A");
const text = readFileSync(readme, "utf8");
const found = said.exec(text);
if (!found) {
  console.error(`${readme}: no "A(n) <size> KB (brotli) runtime" to keep to the build`);
  stale += 1;
} else if (check) {
  if (Math.abs(Number(found[1]) * 1000 - runtime) > 100) {
    console.error(`${readme} says the runtime is ${found[1]} KB brotli; dist/corten.js is ${(runtime / 1000).toFixed(1)} KB: run npm run build:js`);
    stale += 1;
  }
} else {
  const kb = (runtime / 1000).toFixed(1);
  writeFileSync(readme, text.replace(said, `${article(kb)} ${kb} KB (brotli) runtime`));
  console.log(`${readme}: the runtime is ${runtime} B brotli`);
}
process.exit(stale ? 1 : 0);
