// Builds the client code the corten crate embeds, from the sources in crates/corten/js:
//   dist/corten.js  the runtime, minified (the source keeps its comments; browsers get none)
//   dist/format.js  numbers, money and dates for a script (a `%{..}` handler argument): a module of
//                   its own, which only pages whose handlers take a format load
//   dist/field.js   finds the control a handler is given for a form field (a `~` handler argument):
//                   a module of its own, which only pages whose handlers take a field load
//   dist/upload.js  a multipart submit by XMLHttpRequest, for its progress: a module of its own,
//                   which only pages with a form that has an on:corten:progress handler load
//   dist/address.js a data-address form's address in history, and Back and Forward between the
//                   entries it made: a module of its own, which only pages with such a form load
//   dist/keys.js    shortcut() for a page-wide shortcut (`corten/keys`): a module of its own, which
//                   only apps whose scripts import it serve, preloaded with those scripts
//   dist/read.js    read() of a screen's typed data (`corten/read`): a module of its own, served
//                   and preloaded as keys.js is
//   dist/view.js    rows() and the helpers of the generated view classes, which Corten puts at
//                   the start of an app's corten/views module (one script: no extra request)
// esbuild bundles, lowers to ES2022 and minifies each file; terser minifies its output again,
// about 3.6% smaller after compression and a little smaller before it (docs/design.md#choice-runtime-terser).
// `node scripts/build-js.mjs --check` fails when a built file is not what its source builds to, or
// when the runtime's size in README.md ("A(n) <size> KB (gzip) runtime") is not the built file's,
// which a build writes there (scripts/readme-size.mjs), or when a size a guide gives for one of the
// script modules is not the built file's, which a build writes too (scripts/module-sizes.mjs).
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { minify } from "terser";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipped, keep } from "./readme-size.mjs";
import { keepSizes } from "./module-sizes.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const js = join(root, "crates", "corten", "js");
const check = process.argv.includes("--check");
const common = { bundle: true, format: "esm", minify: true, target: "es2022", legalComments: "none", write: false };
/** terser's settings: an ES module, so its top-level names are mangled too. */
const terse = { module: true, ecma: 2022, compress: { passes: 2 } };
const outputs = [
  {
    name: "corten.js",
    entryPoints: [join(js, "corten.js")],
    banner: { js: "// Corten runtime (MIT). Built from crates/corten/js/corten.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "format.js",
    entryPoints: [join(js, "format.js")],
    banner: { js: "// Corten script formats (MIT). Built from crates/corten/js/format.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "field.js",
    entryPoints: [join(js, "field.js")],
    banner: { js: "// Corten fields (MIT). Built from crates/corten/js/field.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "upload.js",
    entryPoints: [join(js, "upload.js")],
    banner: { js: "// Corten upload (MIT). Built from crates/corten/js/upload.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "address.js",
    entryPoints: [join(js, "address.js")],
    banner: { js: "// Corten address (MIT). Built from crates/corten/js/address.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "keys.js",
    entryPoints: [join(js, "keys.js")],
    banner: { js: "// Corten keys (MIT). Built from crates/corten/js/keys.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "read.js",
    entryPoints: [join(js, "read.js")],
    banner: { js: "// Corten read (MIT). Built from crates/corten/js/read.js by scripts/build-js.mjs; do not edit." },
  },
  {
    name: "view.js",
    entryPoints: [join(js, "view.js")],
    // Not a module: corten::script::views_module puts the generated classes after it, in the
    // same module, and they call its helpers by name. Its exports become those names.
    wrap: (text) => {
      const exports = /export\{([^}]*)\};?\s*$/.exec(text);
      if (!exports) throw new Error("view.js: expected esbuild's export list at the end");
      const pairs = exports[1].split(",").map((p) => p.trim().split(/\s+as\s+/));
      const names = pairs.map(([local, name]) => name ?? local);
      const fields = pairs.map(([local, name]) => `${name ?? local}:${local}`);
      const body = text.slice(0, exports.index);
      return `// The app's views (#[component(view)]), generated by Corten. rows() and the helpers: built from crates/corten/js/view.js.\nconst{${names.join(",")}}=(()=>{${body}return{${fields.join(",")}}})();\n`;
    },
  },
];

let stale = 0;
/** The runtime as built now, not as dist/ has it. */
let runtime = "";
/** Each file as built now, by name. */
/** @type {Record<string, string>} */
const built = {};
for (const { name, wrap, banner, ...options } of outputs) {
  const out = join(js, "dist", name);
  const result = await build({ ...common, ...options, outfile: out });
  const code = /** @type {string} */ ((await minify(result.outputFiles[0].text, terse)).code);
  const text = wrap ? wrap(code) : `${banner?.js ?? ""}\n${code}\n`;
  if (name === "corten.js") runtime = text;
  built[name] = text;
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (check) {
    if (current !== text) {
      console.error(`${out} is stale: run npm run build:js`);
      stale += 1;
    }
  } else {
    writeFileSync(out, text);
    console.log(`${out}: ${text.length} B, ${gzipped(text)} B gzip`);
  }
}
const readme = join(root, "README.md");
const before = readFileSync(readme, "utf8");
const kept = keep(before, gzipped(runtime), check);
if (kept.error) {
  console.error(`${readme}: ${kept.error}`);
  stale += 1;
} else if (!check && kept.text !== before) {
  writeFileSync(readme, /** @type {string} */ (kept.text));
}
for (const dir of [join(root, "docs", "guide"), join(root, "skills", "corten", "references")]) {
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".md"))) {
    const path = join(dir, file);
    const guide = readFileSync(path, "utf8");
    const sizes = keepSizes(guide, built, check);
    for (const error of sizes.errors) console.error(`${path}: ${error}`);
    stale += sizes.errors.length;
    if (!check && sizes.text !== guide) writeFileSync(path, sizes.text);
  }
}
process.exit(stale ? 1 : 0);
