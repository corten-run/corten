// Browser smoke test of corten-ui's components, against the ui-gallery example, in Chromium,
// Firefox and WebKit (Playwright's builds: `npx playwright install chromium firefox webkit`).
// Usage: node examples/ui-gallery/smoke.mjs [http://localhost:18482] [chromium|firefox|webkit ...]
import { runSmoke } from "./smoke/helpers.mjs";
import { openGallery, noConsoleErrors, openOrders } from "./smoke/fixtures.mjs";
import { closedTopLayer, modalDialogs, dialogLayout } from "./smoke/dialog.mjs";
import { numberField } from "./smoke/number-field.mjs";
import { comboBox } from "./smoke/combo-box.mjs";
import { checkboxGroup } from "./smoke/checkbox-group.mjs";
import { requiredWhen } from "./smoke/required-when.mjs";
import { inputGroup } from "./smoke/input-group.mjs";
import { button } from "./smoke/button.mjs";
import { formReset } from "./smoke/form-reset.mjs";
import { tabs } from "./smoke/tabs.mjs";
import { sortTable } from "./smoke/sort-table.mjs";
import { choiceGroup } from "./smoke/choice-group.mjs";
import { menuButton, rowMenus } from "./smoke/menu-button.mjs";
import { toaster } from "./smoke/toaster.mjs";
import { copyButton } from "./smoke/copy-button.mjs";
import { printButton } from "./smoke/print-button.mjs";
import { tooltip } from "./smoke/tooltip.mjs";
import { relativeTime } from "./smoke/relative-time.mjs";
import { localTime } from "./smoke/local-time.mjs";
import { alert } from "./smoke/alert.mjs";
import { fields } from "./smoke/fields.mjs";
import { badge } from "./smoke/badge.mjs";
import { tableCells, responsiveTables } from "./smoke/table.mjs";
import { segmentedLinks, segmentedRadios } from "./smoke/segmented.mjs";
import { layout, appSpacing } from "./smoke/layout.mjs";
import { card } from "./smoke/card.mjs";
import { controlSizing } from "./smoke/control-sizing.mjs";
import { meterProgress } from "./smoke/meter-progress.mjs";
import { navBar, touchScroll } from "./smoke/nav-bar.mjs";
import { steps } from "./smoke/steps.mjs";
import { stats } from "./smoke/stats.mjs";
import { statusDot } from "./smoke/status-dot.mjs";
import { previousNext } from "./smoke/previous-next.mjs";
import { switchControl } from "./smoke/switch.mjs";
import { withoutJs } from "./smoke/without-js.mjs";

// Areas run in order and share their pages, routes, and listeners.
await runSmoke(async (browser) => {
  const opened = await openGallery(browser);
  if (!opened) return;
  const { page, bug, errors } = opened;
  await closedTopLayer(page);
  const { qty, qtyButtons } = await numberField(page);
  await comboBox(page, qty);
  const { lastResult, us, shipsValid } = await checkboxGroup(page, browser, bug, errors);
  const { floor, floorRequired } = await requiredWhen(page);
  const { floorGroup } = await inputGroup(floor, page, floorRequired);
  await button(page, floor, lastResult, floorGroup, qty);
  await formReset(us, page, qty, qtyButtons, shipsValid, browser);
  const { tab, period, showing } = await tabs(page);
  await sortTable(page, tab);
  await choiceGroup(page, period, showing, tab);
  await menuButton(page, errors);
  await toaster(page, errors);
  await modalDialogs(browser, errors, page);
  await copyButton(browser, bug, errors);
  await printButton(browser, errors);
  await tooltip(browser, errors);
  await relativeTime(browser, bug);
  await noConsoleErrors(errors);
  await localTime(browser);
  const { orders, ordersErrors } = await openOrders(browser, bug);
  await alert(orders);
  await rowMenus(orders, browser);
  await fields(orders);
  await badge(orders, browser);
  await tableCells(orders);
  await segmentedLinks(orders);
  await layout(orders);
  await card(orders);
  await controlSizing(orders);
  await meterProgress(orders, browser);
  const { start, end, row } = await navBar(orders, browser);
  await responsiveTables(browser, orders);
  await dialogLayout(browser, orders, start, end, row);
  const { draft, forcedMarks } = await steps(orders);
  await touchScroll(draft, forcedMarks, browser);
  await stats(orders);
  await statusDot(orders);
  await appSpacing(orders);
  await previousNext(orders);
  await segmentedRadios(orders);
  await switchControl(orders, ordersErrors);
  await withoutJs(browser);
});
