// #1923's results in one page: node report.mjs <results dir> [bin dir] > floor.md.
// For each comparison directory (aa-same, aa-pad40, aa-pad3100) and each CSV in it: the per-pair
// changes B / A - 1 (stats.mjs) in user+kernel, user and kernel cycles and user instructions per
// request (cycles-<w>.csv), and in each counted event per request (counts-<w>.csv), with what the
// gate's rule (one-sided 95% bound on user+kernel under +1%) would have said of this A/A.
// No margin is tested here; the rule's verdict is reported as a fact about the floor.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { pct, summarize } from "./stats.mjs";

const [, , dir, binArg] = process.argv;
const bin = binArg ?? join(dir, "..", "bin");
const comparisons = [
  ["aa-same", "main-1 against main-2: the same source built twice (A/A identical)"],
  ["aa-pad40", "main-1 against pad40: main with a never-called 40-byte NOP function in router.rs"],
  ["aa-pad3100", "main-1 against pad3100: main with a never-called 3,100-byte NOP function in router.rs"],
];
const out = ["# corten-run/corten#1923: the cycle floor from code placement alone", ""];
out.push("Every row is an A/A: both builds are main's source; A is `main-1` in every comparison. Each change is B / A - 1 per request; the bound is the one-sided 95% upper bound on the median change (the 59th of 100 sorted per-pair changes; the 20th of 30). Range is the smallest to the largest per-pair change. Generated by report.mjs from the CSVs beside it.", "");
const cyc = ["| comparison | workload | pairs | user+kernel median | bound | range | user median | user bound | kernel median | kernel bound | instructions:u median | instructions:u bound | gate rule (bound < +1%) |", "| --- | --- | ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |"];
const ev = ["| comparison | workload | pairs | event per request | A median | B median | median change | bound | range |", "| --- | --- | ---: | --- | ---: | ---: | ---: | ---: | --- |"];
for (const [name] of comparisons) {
  const d = join(dir, name);
  if (!existsSync(d)) continue;
  for (const f of readdirSync(d).filter((x) => /^(cycles|counts)-.*\.csv$/.test(x)).sort()) {
    const s = summarize(join(d, f));
    if (s.pairs === 0) continue;
    const w = f.replace(/^(cycles|counts)-|\.csv$/g, "");
    const m = s.measures;
    if (f.startsWith("cycles-")) {
      const uk = m["cycles user+kernel"], u = m["cycles user"], k = m["cycles kernel"], i = m["instructions user"];
      cyc.push(`| ${name} | ${w} | ${s.pairs} | ${pct(uk.change)} | ${pct(uk.bound)} | ${pct(uk.min)} to ${pct(uk.max)} | ${pct(u.change)} | ${pct(u.bound)} | ${pct(k.change)} | ${pct(k.bound)} | ${pct(i.change)} | ${pct(i.bound)} | ${uk.bound < 0.01 ? "met" : "**not met**"} |`);
    } else {
      for (const [e, x] of Object.entries(m)) ev.push(`| ${name} | ${w} | ${s.pairs} | ${e} | ${x.a.toFixed(3)} | ${x.b.toFixed(3)} | ${pct(x.change)} | ${pct(x.bound)} | ${pct(x.min)} to ${pct(x.max)} |`);
    }
  }
}
out.push("## Cycles (pass 1)", "", ...cyc, "", "## Front-end events (pass 2)", "", ...(ev.length > 2 ? ev : ["Not run, or no event could be counted (host.txt says which)."]), "");
out.push("## The builds", "");
for (const [name, what] of comparisons) out.push(`1. \`${name}\`: ${what}.`);
out.push("");
if (existsSync(join(bin, "sha256.txt"))) out.push("```text", readFileSync(join(bin, "sha256.txt"), "utf8").trim(), "```", "");
for (const v of ["main-2", "pad40", "pad3100"]) {
  const f = join(bin, `layout-${v}.txt`);
  if (existsSync(f)) out.push(`Layout of ${v} against main-1 (layout.mjs):`, "", "```text", readFileSync(f, "utf8").trim(), "```", "");
}
console.log(out.join("\n"));