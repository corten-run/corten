//
// Usage: <bin> <port> plain
//   GET /private         the record page for one visitor (about 6 KB), not kept
//   GET /unstaged        a route that says `unstaged`, a short str out
// PROBE_ALLOCATOR=jemalloc (or glibc) makes the probe refuse to start unless /proc/self/maps shows
